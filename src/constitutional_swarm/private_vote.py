def _verify_commit_signature(record: CommitRecord) -> None:
    try:
        pub = Ed25519PublicKey.from_public_bytes(record.voter)
    except ValueError as exc:
        raise InvalidCommitError(f"bad voter pubkey: {exc}") from exc
    payload = _signing_payload_commit(
        record.version,
        record.epoch,
        record.subject,
        record.voter,
        record.commit,
        record.nullifier,
        record.proof_scheme,
        record.validity_proof,
    )
    try:
        pub.verify(record.signature, payload)
    except InvalidSignature as exc:
        raise InvalidCommitError("bad commit signature") from exc


def _validate_commit_record(
    record: CommitRecord,
    *,
    epoch: bytes,
    subject: bytes,
    eligible_voters: frozenset[bytes],
    provers: Mapping[str, ValidityProver],
    strict_v2: bool,
) -> None:
    """Validate every context-bound invariant for a commit record."""
    if record.version not in _SUPPORTED_VERSIONS:
        raise InvalidCommitError(f"unsupported commit version {record.version}")
    if record.epoch != epoch or record.subject != subject:
        raise InvalidCommitError("epoch/subject mismatch")
    if record.voter not in eligible_voters:
        raise InvalidCommitError("ineligible voter")
    try:
        canonical_nullifier = compute_nullifier(
            voter_pub=record.voter, epoch=record.epoch, subject=record.subject
        )
    except ValueError as exc:
        raise InvalidCommitError(str(exc)) from exc
    if record.nullifier != canonical_nullifier:
        raise InvalidCommitError("noncanonical nullifier")
    _verify_commit_signature(record)
    if strict_v2 and record.version < _V2_VERSION:
        raise InvalidCommitError("strict_v2: legacy v1 commit rejected")

    has_scheme = record.proof_scheme is not None
    has_proof = record.validity_proof is not None
    if record.version < _V2_VERSION:
        if has_scheme or has_proof:
            raise InvalidCommitError("v1 commit cannot carry v2 proof fields")
        return
    if has_scheme != has_proof:
        raise InvalidCommitError(
            "v2 commit: proof_scheme and validity_proof must both be set or both absent"
        )
    if has_scheme and (record.proof_scheme == "" or record.validity_proof == b""):
        raise InvalidCommitError("v2 proof_scheme and validity_proof must be non-empty")
    if not has_scheme:
        if strict_v2:
            raise InvalidCommitError("strict_v2 requires proof_scheme and validity_proof")
        return

    assert record.proof_scheme is not None
    assert record.validity_proof is not None
    prover = provers.get(record.proof_scheme)
    if prover is None:
        raise InvalidCommitError(f"no verifier for scheme {record.proof_scheme!r}")
    if prover.scheme_id != record.proof_scheme:
        raise InvalidCommitError(
            f"verifier scheme mismatch: registered {record.proof_scheme!r}, "
            f"verifier declares {prover.scheme_id!r}"
        )
    if strict_v2 and getattr(prover, "provides_validity_assurance", None) is not True:
        raise InvalidCommitError("strict_v2 verifier provides no validity assurance")
    statement = ValidityStatement(
        epoch=record.epoch,
        subject=record.subject,
        voter=record.voter,
        commit=record.commit,
        nullifier=record.nullifier,
    )
    if prover.verify(statement, record.validity_proof) is not True:
        raise InvalidCommitError("invalid validity proof")


def _verify_reveal_against_commit(reveal: RevealRecord, commit_record: CommitRecord) -> None:
    expected = _commit_digest(
        reveal.choice,
        reveal.nonce,
        commit_record.epoch,
        commit_record.subject,
        commit_record.voter,
    )
    if expected != commit_record.commit:
        raise InvalidRevealError("reveal does not open the commit")
    try:
        pub = Ed25519PublicKey.from_public_bytes(commit_record.voter)
    except ValueError as exc:
        raise InvalidRevealError(f"bad voter pubkey: {exc}") from exc
    payload = _signing_payload_reveal(reveal.commit, reveal.choice, reveal.nonce)
    try:
        pub.verify(reveal.signature, payload)
    except InvalidSignature as exc:
        raise InvalidRevealError("bad reveal signature") from exc


@dataclass(frozen=True)
class PrivateTally:
    """Deterministic tally result for an epoch/subject pair."""

    epoch: bytes
    subject: bytes
    totals: Mapping[BallotChoice, int]
    accepted: tuple[bytes, ...] = field(default_factory=tuple)
    rejected: tuple[tuple[bytes, str], ...] = field(default_factory=tuple)

    @property
    def total_valid(self) -> int:
        return sum(self.totals.values())

    def to_dict(self) -> dict[str, object]:
        return {
            "epoch": self.epoch.hex(),
            "subject": self.subject.hex(),
            "totals": {k.value: v for k, v in self.totals.items()},
            "accepted": [c.hex() for c in self.accepted],
            "rejected": [(c.hex(), reason) for c, reason in self.rejected],
        }


def tally(
    commits: Iterable[CommitRecord],
    reveals: Iterable[RevealRecord],
    *,
    epoch: bytes,
    subject: bytes,
    eligible_voters: frozenset[bytes],
    require_all_revealed: bool = False,
    provers: Mapping[str, ValidityProver] | None = None,
    strict_v2: bool = False,
) -> PrivateTally:
    """Audit commits + reveals and produce a deterministic tally.

    Rules:
      * Every commit must belong to an eligible Ed25519 key and carry
        that key's canonical nullifier.
      * Each eligible key contributes at most one ballot.
      * A commit with no matching reveal is counted as missing.
      * Each reveal must open its commit and its signature must verify.
      * Only commits that are accepted *and* have a valid reveal
        contribute to totals.
      * Strict v2 requires a proof and a registered verifier whose
        scheme matches and which explicitly advertises real validity
        assurance.
    """
    eligible_voters = _validate_eligible_voters(eligible_voters)
    commits = list(commits)
    reveals_by_commit: dict[bytes, list[RevealRecord]] = {}
    for rv in reveals:
        # Collect all reveals per commit — the valid one is found during tally.
        reveals_by_commit.setdefault(rv.commit, []).append(rv)

    seen_nullifiers: set[bytes] = set()
    seen_voters: set[bytes] = set()
    accepted: list[tuple[tuple[bytes, bytes], CommitRecord]] = []
    rejected: list[tuple[bytes, str]] = []
    provers_map: Mapping[str, ValidityProver] = provers or {}

    # The voter key breaks digest ties, making first-wins deterministic even
    # when an eligible attacker copies another voter's digest.
    for c in sorted(commits, key=lambda r: (r.commit, r.voter)):
        try:
            _validate_commit_record(
                c,
                epoch=epoch,
                subject=subject,
                eligible_voters=eligible_voters,
                provers=provers_map,
                strict_v2=strict_v2,
            )
        except InvalidCommitError as exc:
            rejected.append((c.commit, str(exc)))
            continue
        if c.voter in seen_voters:
            rejected.append((c.commit, "duplicate voter"))
            continue
        # Defense in depth for future nullifier derivations or a digest collision.
        if c.nullifier in seen_nullifiers:
            rejected.append((c.commit, "duplicate nullifier"))
            continue
        seen_voters.add(c.voter)
        seen_nullifiers.add(c.nullifier)
        accepted.append(((c.voter, c.commit), c))

    totals: dict[BallotChoice, int] = {ch: 0 for ch in BallotChoice}
    tallied_commits: list[bytes] = []
    tallied_ballots: set[tuple[bytes, bytes]] = set()
    digest_counts: dict[bytes, int] = {}
    for _, commit_record in accepted:
        digest_counts[commit_record.commit] = digest_counts.get(commit_record.commit, 0) + 1
    for ballot_id, c in accepted:
        rvs = reveals_by_commit.get(c.commit, [])
        if not rvs:
            reason = "missing reveal"
            if digest_counts[c.commit] > 1:
                reason = f"{reason} for voter {c.voter.hex()}"
            rejected.append((c.commit, reason))
            continue
        # Try all reveals for this commit in arrival order; accept the first valid one.
        verified_rv: RevealRecord | None = None
        last_exc_msg = ""
        for rv in rvs:
            try:
                _verify_reveal_against_commit(rv, c)
                verified_rv = rv
                break
            except InvalidRevealError as exc:
                last_exc_msg = str(exc)
        if verified_rv is None:
            reason = last_exc_msg or "invalid reveal"
            if digest_counts[c.commit] > 1:
                reason = f"{reason} for voter {c.voter.hex()}"
            rejected.append((c.commit, reason))
            continue
        totals[verified_rv.choice] += 1
        tallied_commits.append(c.commit)
        tallied_ballots.add(ballot_id)

    if require_all_revealed:
        # A commit counts as "revealed" only if it has a *valid* reveal that
        # opens it — the presence of a malformed or non-opening reveal (which
        # is dropped in the loop above) does not satisfy the gate.
        missing = [ballot_id for ballot_id, _ in accepted if ballot_id not in tallied_ballots]
        if missing:
            raise MissingRevealError(
                f"{len(missing)} accepted ballots have no valid reveal"
            )

    return PrivateTally(
        epoch=epoch,
        subject=subject,
        totals=totals,
        accepted=tuple(tallied_commits),
        rejected=tuple(rejected),
    )


# ---------------------------------------------------------------------------
# Stateful helper (nice-to-have for tests / integration)
# ---------------------------------------------------------------------------


@dataclass(frozen=True, eq=False)
class PrivateBallotBox:
    """In-memory ballot box tracking commits then reveals for one epoch/subject.

    Thin wrapper around :func:`tally` that enforces the two-phase
    commit/reveal discipline. Useful for tests and for embedding in
    mesh services.
    """

    epoch: bytes
    subject: bytes
    eligible_voters: frozenset[bytes]
    provers: Mapping[str, ValidityProver] | None = field(default=None, repr=False)
    strict_v2: bool = False
    _commits: dict[tuple[bytes, bytes], CommitRecord] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )
    _nullifiers: dict[bytes, tuple[bytes, bytes]] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )
    _voters: dict[bytes, tuple[bytes, bytes]] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )
    _reveals: dict[tuple[bytes, bytes], RevealRecord] = field(
        default_factory=dict, init=False, repr=False, compare=False
    )
    _closed_commits: bool = field(default=False, init=False, repr=False, compare=False)
    _lock: Lock = field(default_factory=Lock, init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "eligible_voters", _validate_eligible_voters(self.eligible_voters))
        configured_provers = {} if self.provers is None else dict(self.provers)
        object.__setattr__(self, "provers", MappingProxyType(configured_provers))

    def submit_commit(self, record: CommitRecord) -> None:
        # Proof verification may invoke third-party code, so perform it before
        # acquiring the state lock. Configuration is immutable after init.
        provers = self.provers
        assert provers is not None
        _validate_commit_record(
            record,
            epoch=self.epoch,
            subject=self.subject,
            eligible_voters=self.eligible_voters,
            provers=provers,
            strict_v2=self.strict_v2,
        )
        ballot_id = (record.voter, record.commit)
        with self._lock:
            if self._closed_commits:
                raise InvalidCommitError("commit phase already closed")
            if ballot_id in self._commits:
                raise InvalidCommitError("duplicate ballot")
            if record.voter in self._voters:
                raise DoubleVoteError("duplicate voter")
            # Defense in depth for future nullifier derivations or a digest collision.
            if record.nullifier in self._nullifiers:
                raise DoubleVoteError("nullifier reuse")
            self._commits[ballot_id] = record
            self._nullifiers[record.nullifier] = ballot_id
            self._voters[record.voter] = ballot_id

    def close_commit_phase(self) -> None:
        with self._lock:
            object.__setattr__(self, "_closed_commits", True)

    def submit_reveal(self, record: RevealRecord) -> None:
        with self._lock:
            if not self._closed_commits:
                raise InvalidRevealError("reveal phase not open")
            candidates = sorted(
                (
                    (ballot_id, commit_record)
                    for ballot_id, commit_record in self._commits.items()
                    if commit_record.commit == record.commit
                ),
                key=lambda item: item[0],
            )
        if not candidates:
            raise InvalidRevealError("no matching commit")

        matched_id: tuple[bytes, bytes] | None = None
        last_error = "reveal does not match any voter-bound commit"
        for ballot_id, commit_record in candidates:
            try:
                _verify_reveal_against_commit(record, commit_record)
                matched_id = ballot_id
                break
            except InvalidRevealError as exc:
                last_error = str(exc)
        if matched_id is None:
            raise InvalidRevealError(last_error)
        with self._lock:
            self._reveals.setdefault(matched_id, record)

    def tally(
        self,
        *,
        require_all_revealed: bool = False,
    ) -> PrivateTally:
        with self._lock:
            commits = tuple(self._commits.values())
            reveals = tuple(self._reveals.values())
        provers = self.provers
        assert provers is not None
        return tally(
            commits,
            reveals,
            epoch=self.epoch,
            subject=self.subject,
            eligible_voters=self.eligible_voters,
            require_all_revealed=require_all_revealed,
            provers=provers,
            strict_v2=self.strict_v2,
        )
