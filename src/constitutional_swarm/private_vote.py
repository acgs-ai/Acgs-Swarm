# Pure-function primitives
# ---------------------------------------------------------------------------


def _digest(*parts: bytes) -> bytes:
    h = hashlib.sha256()
    for p in parts:
        h.update(len(p).to_bytes(4, "big"))
        h.update(p)
    return h.digest()


def _validate_voter_pub(voter_pub: bytes) -> None:
    if not isinstance(voter_pub, bytes) or len(voter_pub) != 32:
        raise ValueError("voter_pub must be a 32-byte Ed25519 public key")
    try:
        Ed25519PublicKey.from_public_bytes(voter_pub)
    except ValueError as exc:
        raise ValueError(f"invalid Ed25519 public key: {exc}") from exc


def _validate_eligible_voters(eligible_voters: frozenset[bytes]) -> frozenset[bytes]:
    if not isinstance(eligible_voters, frozenset):
        raise TypeError("eligible_voters must be a frozenset of Ed25519 public keys")
    normalized = frozenset(eligible_voters)
    for voter_pub in normalized:
        _validate_voter_pub(voter_pub)
    return normalized


def compute_nullifier(*, voter_pub: bytes, epoch: bytes, subject: bytes) -> bytes:
    """Return the canonical double-vote tag for one registered voter key.

    The keyword-only public-key argument intentionally makes stale
    secret-based calls fail loudly instead of treating a 32-byte secret
    as an Ed25519 identity.
    """
    _validate_voter_pub(voter_pub)
    return _digest(b"acgs-null-v2", voter_pub, epoch, subject)


def _commit_digest(
    choice: BallotChoice,
    nonce: bytes,
    epoch: bytes,
    subject: bytes,
    voter_pub: bytes,
) -> bytes:
    return _digest(
        b"acgs-commit-v2",
        choice.value.encode("ascii"),
        nonce,
        epoch,
        subject,
        voter_pub,
    )


def _signing_payload_commit(
    version: int,
    epoch: bytes,
    subject: bytes,
    voter_pub: bytes,
    commit: bytes,
    nullifier: bytes,
    proof_scheme: str | None,
    validity_proof: bytes | None,
) -> bytes:
    scheme_present = b"\x01" if proof_scheme is not None else b"\x00"
    proof_present = b"\x01" if validity_proof is not None else b"\x00"
    try:
        encoded_proof_scheme = b"" if proof_scheme is None else proof_scheme.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise InvalidCommitError("proof_scheme must be valid UTF-8") from exc
    return _digest(
        b"acgs-commit-sig-v2",
        version.to_bytes(4, "big"),
        epoch,
        subject,
        voter_pub,
        commit,
        nullifier,
        scheme_present,
        encoded_proof_scheme,
        proof_present,
        b"" if validity_proof is None else validity_proof,
    )


def _signing_payload_reveal(commit: bytes, choice: BallotChoice, nonce: bytes) -> bytes:
    return _digest(b"acgs-reveal-sig-v1", commit, choice.value.encode("ascii"), nonce)


